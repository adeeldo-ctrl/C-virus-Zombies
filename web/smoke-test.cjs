const http = require("node:http");
const fs = require("node:fs");
const path = require("node:path");
const { chromium } = require("playwright");
const root = path.resolve(__dirname, "dist");
const mime = {".html":"text/html",".js":"text/javascript",".css":"text/css"};
const server = http.createServer((req,res) => {
  const pathname = decodeURIComponent(new URL(req.url,"http://localhost").pathname);
  const requested = pathname === "/" ? "/index.html" : pathname;
  const file = path.resolve(root, "." + requested);
  if (!file.startsWith(root + path.sep) && file !== path.join(root,"index.html")) {res.writeHead(403);return res.end("Forbidden");}
  fs.readFile(file,(err,data)=>{if(err){res.writeHead(404);return res.end("Not found");}res.writeHead(200,{"content-type":mime[path.extname(file)]||"application/octet-stream"});res.end(data);});
});
(async()=>{
  await new Promise(resolve=>server.listen(4173,"127.0.0.1",resolve));
  const browser=await chromium.launch({headless:true,args:["--use-gl=swiftshader","--enable-webgl"]});
  const page=await browser.newPage({viewport:{width:1280,height:800}});
  const errors=[];
  page.on("pageerror",e=>errors.push(e.message));
  page.on("console",m=>{if(m.type()==="error")errors.push(m.text());});
  page.on("requestfailed",r=>errors.push("Request failed: "+r.url()+" "+(r.failure()?.errorText||"")));
  page.on("response",r=>{if(r.status()>=400)errors.push("HTTP "+r.status()+": "+r.url());});
  try {
    await page.goto("http://127.0.0.1:4173/",{waitUntil:"domcontentloaded"});
    await page.waitForTimeout(2500);
    if(!await page.evaluate(()=>!!window.__CVIRUS_DEBUG__))throw new Error("Desktop scene initialization failed: "+errors.join(" | "));
    await page.waitForFunction(()=>window.__CVIRUS_DEBUG__.scene.isReady(),null,{timeout:10000});
    const initial=await page.evaluate(()=>({canvas:!!document.querySelector("#game"),zombies:window.__CVIRUS_DEBUG__.zombies.length,playerZ:window.__CVIRUS_DEBUG__.player.position.z}));
    if(!initial.canvas||initial.zombies!==5)throw new Error("Initial scene assertions failed: "+JSON.stringify(initial));
    const heroParts=await page.evaluate(()=>window.__CVIRUS_DEBUG__.heroRig.heroParts.length);
    if(heroParts<10)throw new Error("Original modular hero character parts are missing.");
    const interiors=await page.evaluate(()=>window.__CVIRUS_DEBUG__.interiorRooms.map(r=>r.type));
    if(interiors.join(",")!=="CLINIC,SHOP,POLICE")throw new Error("Walk-in city interiors are missing: "+interiors.join(","));
    await page.locator("#game").focus();
    await page.keyboard.down("w");
    await page.waitForFunction(()=>window.__CVIRUS_DEBUG__.keys.w===true,null,{timeout:3000});
    await page.waitForTimeout(250);
    await page.keyboard.up("w");
    const moved=await page.evaluate(()=>window.__CVIRUS_DEBUG__.player.position.z);
    if(!(moved<initial.playerZ))throw new Error("Forward input did not move player toward objective.");
    const normalDistance=initial.playerZ-moved;
    const sprintStart=await page.evaluate(()=>window.__CVIRUS_DEBUG__.player.position.z);
    const staminaBefore=await page.evaluate(()=>window.__CVIRUS_DEBUG__.state.stamina);
    await page.keyboard.down("w");await page.keyboard.down("Shift");await page.waitForTimeout(450);await page.keyboard.up("w");await page.keyboard.up("Shift");
    const sprintEnd=await page.evaluate(()=>window.__CVIRUS_DEBUG__.player.position.z);
    if(!(sprintStart-sprintEnd>normalDistance*.8))throw new Error("Sprint input did not move the player.");
    const staminaAfter=await page.evaluate(()=>window.__CVIRUS_DEBUG__.state.stamina);
    if(!(staminaAfter<staminaBefore))throw new Error("Sprint did not consume stamina.");
    const jumpStart=await page.evaluate(()=>window.__CVIRUS_DEBUG__.player.position.y);
    await page.keyboard.press("Space");await page.waitForTimeout(180);
    const jumpPeak=await page.evaluate(()=>window.__CVIRUS_DEBUG__.player.position.y);
    if(!(jumpPeak>jumpStart+.3))throw new Error("Jump input did not raise the player.");
    await page.waitForTimeout(1000);
    const sideStart=await page.evaluate(()=>{const p=window.__CVIRUS_DEBUG__.player;p.position.x=6;return p.position.x;});
    await page.keyboard.down("d");await page.waitForTimeout(800);await page.keyboard.up("d");
    const sideEnd=await page.evaluate(()=>window.__CVIRUS_DEBUG__.player.position.x);
    if(!(sideEnd<7.4&&sideEnd>sideStart))throw new Error("Street boundary collision did not constrain lateral movement.");
    // Verify vehicle proximity guidance, enter/exit, and usable backpack supplies.
    await page.evaluate(()=>{const d=window.__CVIRUS_DEBUG__;d.player.position.set(d.vehicle.position.x,.95,d.vehicle.position.z+3.2);});
    await page.waitForTimeout(80);
    if(!(await page.locator("#vehicle-prompt").isVisible()))throw new Error("Sedan enter prompt did not appear nearby.");
    await page.locator("#drive").click();
    if(!await page.evaluate(()=>window.__CVIRUS_DEBUG__.driving))throw new Error("Vehicle enter interaction failed.");
    await page.waitForFunction(()=>document.getElementById("vehicle-prompt").textContent.includes("EXIT"),null,{timeout:3000});
    if(!(await page.locator("#vehicle-prompt").innerText()).includes("EXIT"))throw new Error("Vehicle exit prompt missing.");
    await page.locator("#drive").click();
    if(await page.evaluate(()=>window.__CVIRUS_DEBUG__.driving))throw new Error("Vehicle exit interaction failed.");
    await page.locator("#inventory-button").click();
    await page.evaluate(()=>{const d=window.__CVIRUS_DEBUG__;d.state.health=50;d.state.inventory.medicine=1;document.getElementById("health").style.width="50%";document.getElementById("use-medicine").disabled=false;});
    await page.locator("#use-medicine").click();
    const consumed=await page.evaluate(()=>({health:window.__CVIRUS_DEBUG__.state.health,medicine:window.__CVIRUS_DEBUG__.state.inventory.medicine}));
    if(consumed.health!==80||consumed.medicine!==0)throw new Error("Backpack medicine did not restore health and consume one item.");
    await page.locator("#inventory-button").click();
    // Walk from the street through the clinic doorway and confirm the interior prompt.
    await page.evaluate(()=>{const d=window.__CVIRUS_DEBUG__;d.state.yaw=0;d.player.position.set(-1.4,.95,18);});
    await page.keyboard.down("a");await page.waitForTimeout(850);await page.keyboard.up("a");
    const clinicEntry=await page.evaluate(()=>({x:window.__CVIRUS_DEBUG__.player.position.x,prompt:document.getElementById("building-prompt").textContent}));
    if(!(clinicEntry.x<-3.5&&clinicEntry.prompt.includes("CLINIC")))throw new Error("Player could not walk through the clinic doorway: "+JSON.stringify(clinicEntry));
    await page.evaluate(()=>{const d=window.__CVIRUS_DEBUG__;d.pickups.forEach(p=>{p.collected=true;p.mesh.setEnabled(false);p.marker.setEnabled(false);});d.state.supplies=4;document.getElementById("supplies").textContent="4";d.player.position.copyFrom(d.safe.position);});
    await page.waitForFunction(()=>window.__CVIRUS_DEBUG__.state.safe,{timeout:5000});
    const message=await page.locator("#message").innerText();
    if(!message.includes("Safe zone reached"))throw new Error("Safe-zone completion message missing.");
    if(errors.length)throw new Error("Desktop browser errors: "+errors.join(" | "));
    const mobile=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1,isMobile:true,hasTouch:true});
    mobile.on("pageerror",e=>errors.push(e.message));
    mobile.on("console",m=>{if(m.type()==="error")errors.push(m.text());});
    mobile.on("requestfailed",r=>errors.push("Mobile request failed: "+r.url()+" "+(r.failure()?.errorText||"")));
    await mobile.goto("http://127.0.0.1:4173/",{waitUntil:"domcontentloaded"});
    await mobile.waitForTimeout(2500);
    if(!await mobile.evaluate(()=>!!window.__CVIRUS_DEBUG__))throw new Error("Mobile scene initialization failed: "+errors.join(" | "));
    await mobile.waitForFunction(()=>window.__CVIRUS_DEBUG__.scene.isReady(),null,{timeout:10000});
    const touch=await mobile.context().newCDPSession(mobile);
    const beforeTouch=await mobile.evaluate(()=>window.__CVIRUS_DEBUG__.player.position.z);
    await touch.send("Input.dispatchTouchEvent",{type:"touchStart",touchPoints:[{x:76,y:768,id:1}]});
    await touch.send("Input.dispatchTouchEvent",{type:"touchMove",touchPoints:[{x:76,y:728,id:1}]});
    await mobile.waitForTimeout(450);
    await touch.send("Input.dispatchTouchEvent",{type:"touchEnd",touchPoints:[]});
    const afterTouch=await mobile.evaluate(()=>window.__CVIRUS_DEBUG__.player.position.z);
    if(!(afterTouch<beforeTouch))throw new Error("Mobile touch joystick did not move player forward.");
    const yawBefore=await mobile.evaluate(()=>window.__CVIRUS_DEBUG__.state.yaw);
    await touch.send("Input.dispatchTouchEvent",{type:"touchStart",touchPoints:[{x:330,y:500,id:2}]});
    await touch.send("Input.dispatchTouchEvent",{type:"touchMove",touchPoints:[{x:350,y:500,id:2}]});
    await touch.send("Input.dispatchTouchEvent",{type:"touchEnd",touchPoints:[]});
    const yawAfter=await mobile.evaluate(()=>window.__CVIRUS_DEBUG__.state.yaw);
    if(yawAfter===yawBefore)throw new Error("Mobile right-side camera look did not respond.");
    const mobileJumpStart=await mobile.evaluate(()=>window.__CVIRUS_DEBUG__.player.position.y);
    await mobile.locator("#jump").evaluate(el=>el.dispatchEvent(new PointerEvent("pointerdown",{bubbles:true,pointerId:7,pointerType:"touch"})));
    await mobile.waitForTimeout(180);
    const mobileJumpPeak=await mobile.evaluate(()=>window.__CVIRUS_DEBUG__.player.position.y);
    if(!(mobileJumpPeak>mobileJumpStart+.3))throw new Error("Mobile jump button did not work.");
    if(!await mobile.locator("#stamina").count())throw new Error("Mobile stamina HUD missing.");
    if(errors.length)throw new Error("Browser errors: "+errors.join(" | "));
    console.log("PASS: desktop scene, walkers, movement, sprint, jump, collision, vehicle enter/exit, backpack medicine, safe-zone objective; mobile viewport, joystick, camera-look and jump controls; no browser errors.");
  } finally {await browser.close();await new Promise(resolve=>server.close(resolve));}
})().catch(e=>{console.error(e);process.exit(1);});
